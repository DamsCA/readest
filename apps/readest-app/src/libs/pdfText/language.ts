const SETS = Object.fromEntries(
  Object.entries(STOPWORDS).map(([lang, words]) => [lang, new Set(words)]),
) as Record<string, Set<string>>;

export function detectLanguage(text: string): string {
  const words = text.toLowerCase().match(/[\p{L}']+/gu) ?? [];
  if (words.length < 20) return '';
  const scores: Array<[string, number]> = Object.keys(SETS).map((lang) => {
    const set = SETS[lang]!;
    let score = 0;
    for (const w of words) if (set.has(w)) score++;
    return [lang, score];
  });
  scores.sort((a, b) => b[1] - a[1]);
  const [best, second] = scores;
  if (!best || best[1] < 8) return '';
  if (second && best[1] < second[1] * 1.3) return '';
  return best[0];
}

const RTL_LANGUAGES = new Set(['ar', 'he', 'fa', 'ur', 'yi']);
export const isRtlLanguage = (lang: string) => RTL_LANGUAGES.has(lang.split('-')[0]!.toLowerCase());
